// Expõe cada cor do Tailwind como variável CSS global, ex.: var(--blue-500).
// Os tokens do shadcn (primary, accent...) já apontam para var(--...) e são
// pulados; sem esse filtro sairia "--primary: hsl(var(--primary))", circular.
function addVariablesForColors({ addBase, theme }) {
  let allColors = flattenColorPalette(theme("colors"));
  let newVars = Object.fromEntries(
    Object.entries(allColors)
      .filter(([, val]) => typeof val === "string" && !val.includes("var("))
      .map(([key, val]) => [`--${key}`, val])
  );

  addBase({
    ":root": newVars,
  });
}
